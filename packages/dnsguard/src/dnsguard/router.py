"""Optional: push the active rule set to a router that runs dnsmasq.

This is a generic driver. Everything it touches - host, user, paths, how the
router is restarted - comes from configuration, and nothing is hardcoded. It
works over SSH with the key or agent the machine already has, so no
credential is ever stored in the repository or in the configuration file.

The router is a *second* enforcement point, not a replacement for the
service: a dnsmasq ``address=`` rule cannot express a KEEP exception, and it
cannot express a regular expression. Deploying to a router therefore makes
the rule set coarser, never finer.
"""

import hashlib
import json
import os
import shutil
import subprocess

DEFAULT_CONFIG = {
    "host": "",
    "port": 22,
    "user": "root",
    "ssh_key": "",
    "remote_dir": "/etc/dnsmasq.d",
    "remote_file": "toney.conf",
    "service": "dnsmasq",
    "restart_command": "",
    "sudo": False,
    "timeout_s": 20,
    "backup_dir": "",
}


class RouterError(RuntimeError):
    """Raised when the router cannot be reached or the deployment failed."""


class RouterDriver:
    """Deploys and rolls back a dnsmasq rule file on a remote router."""

    def __init__(self, config=None, runner=None):
        self.config = dict(DEFAULT_CONFIG)
        self.config.update(config or {})
        self.runner = runner or self._run
        self._rules = []

    # -- configuration ----------------------------------------------------- #

    def configured(self):
        return bool(self.config.get("host"))

    def describe(self):
        return {
            "host": self.config.get("host"),
            "port": self.config.get("port"),
            "user": self.config.get("user"),
            "remote_file": self.remote_path(),
            "service": self.config.get("service"),
            "configured": self.configured(),
        }

    def remote_path(self):
        return os.path.join(self.config.get("remote_dir", ""),
                            self.config.get("remote_file", ""))

    def backup_dir(self):
        directory = self.config.get("backup_dir")
        if not directory:
            directory = os.path.join(os.path.expanduser("~"), ".local", "state",
                                     "toney", "router-backups")
        return os.path.abspath(os.path.expanduser(directory))

    # -- rule translation -------------------------------------------------- #

    @staticmethod
    def build_include(rules):
        """Translate rules into a dnsmasq include file.

        Returns (text, skipped) where skipped counts the rules that dnsmasq
        cannot express.
        """
        lines = ["# generated by dnsguard - do not edit by hand",
                 "# format: address=/<domain>/0.0.0.0"]
        skipped = 0
        for rule in rules:
            if rule.action != "block":
                continue
            if rule.kind != "domain":
                skipped += 1
                continue
            lines.append("address=/%s/0.0.0.0" % rule.value)
        return "\n".join(lines) + "\n", skipped

    # -- transport --------------------------------------------------------- #

    def _ssh_base(self):
        command = ["ssh",
                   "-o", "BatchMode=yes",
                   "-o", "StrictHostKeyChecking=accept-new",
                   "-p", str(self.config.get("port", 22))]
        key = self.config.get("ssh_key")
        if key:
            command += ["-i", os.path.expanduser(key)]
        command.append("%s@%s" % (self.config.get("user", "root"),
                                  self.config.get("host")))
        return command

    def _run(self, command, stdin=None, timeout=None):
        try:
            completed = subprocess.run(
                command,
                input=stdin,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                timeout=timeout or self.config.get("timeout_s", 20),
                check=False)
        except subprocess.TimeoutExpired:
            raise RouterError("the router did not answer in time")
        except OSError as exc:
            raise RouterError("cannot run %s: %s" % (command[0], exc))
        if completed.returncode != 0:
            message = completed.stderr.decode("utf-8", "replace").strip()
            raise RouterError(message or "command failed: %s" % " ".join(command))
        return completed.stdout.decode("utf-8", "replace")

    def _run_on_router(self, shell_command, stdin=None):
        return self.runner(self._ssh_base() + [shell_command], stdin=stdin)

    # -- operations -------------------------------------------------------- #

    def status(self, rules=None):
        """Report whether the generated file is installed on the router."""
        if not self.configured():
            return {"configured": False, "installed": False, "matches": False}
        path = self.remote_path()
        remote = self._run_on_router(
            "if [ -f %s ]; then cat %s; else echo __MISSING__; fi" % (path, path))
        installed = "__MISSING__" not in remote
        active = rules if rules is not None else self._rules
        text, _ = self.build_include(active)
        return {
            "configured": True,
            "installed": installed,
            "remote_path": path,
            "bytes": len(remote),
            "matches": installed and remote == text,
            "local_hash": hashlib.sha256(text.encode("utf-8")).hexdigest(),
            "remote_hash": hashlib.sha256(remote.encode("utf-8")).hexdigest() if installed else None,
        }

    def deploy(self, rules):
        """Write the rule file on the router and restart dnsmasq."""
        if not self.configured():
            raise RouterError("no router is configured")
        self._rules = rules
        text, skipped = self.build_include(rules)
        path = self.remote_path()
        previous = self._read_remote(path)
        self._backup(previous)
        self._run_on_router("mkdir -p %s" % os.path.dirname(path))
        self._run_on_router("cat > %s" % path, stdin=text.encode("utf-8"))
        self._restart()
        return {
            "deployed": True,
            "remote_path": path,
            "rules": sum(1 for r in rules if r.action == "block" and r.kind == "domain"),
            "skipped": skipped,
            "bytes": len(text),
        }

    def rollback(self):
        """Restore the previous file (or remove ours) and restart dnsmasq."""
        if not self.configured():
            raise RouterError("no router is configured")
        path = self.remote_path()
        backup = self._latest_backup()
        if backup is None:
            self._run_on_router("rm -f %s" % path)
            self._restart()
            return {"rolled_back": True, "restored": None, "removed": True}
        if hasattr(backup, "read_bytes"):
            content = backup.read_bytes()
        else:
            with open(backup, "rb") as handle:
                content = handle.read()
        self._run_on_router("cat > %s" % path, stdin=content)
        self._restart()
        return {"rolled_back": True, "restored": str(backup), "removed": False}

    def _read_remote(self, path):
        try:
            return self._run_on_router("cat %s 2>/dev/null || true" % path)
        except RouterError:
            return ""

    def _backup(self, content):
        directory = self.backup_dir()
        os.makedirs(directory, exist_ok=True)
        stamp = self._stamp()
        with open(os.path.join(directory, "router-%s.conf" % stamp), "w",
                  encoding="utf-8") as handle:
            handle.write(content)
        self._prune_backups(directory)

    def _latest_backup(self):
        directory = self.backup_dir()
        if not os.path.isdir(directory):
            return None
        names = sorted(name for name in os.listdir(directory)
                       if name.startswith("router-") and name.endswith(".conf"))
        if not names:
            return None
        return os.path.join(directory, names[-1])

    @staticmethod
    def _prune_backups(directory, keep=10):
        names = sorted(name for name in os.listdir(directory)
                       if name.startswith("router-") and name.endswith(".conf"))
        for name in names[:-keep]:
            try:
                os.unlink(os.path.join(directory, name))
            except OSError:
                pass

    def _stamp(self):
        import time
        return time.strftime("%Y%m%d-%H%M%S", time.gmtime())

    def _restart(self):
        command = self.config.get("restart_command")
        if not command:
            service = self.config.get("service", "dnsmasq")
            command = "/etc/init.d/%s restart" % service
        if self.config.get("sudo"):
            command = "sudo -n %s" % command
        self._run_on_router(command)
