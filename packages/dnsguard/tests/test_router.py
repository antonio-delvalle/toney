import os
import tempfile
import unittest

from dnsguard import rules as rules_mod
from dnsguard.router import RouterDriver, RouterError


class FakeRunner:
    def __init__(self, answers=None):
        self.answers = answers or {}
        self.calls = []

    def __call__(self, command, stdin=None, timeout=None):
        self.calls.append((command, stdin))
        for needle, answer in self.answers.items():
            if needle in " ".join(command):
                return answer
        return ""


class BuildIncludeTests(unittest.TestCase):
    def _rules(self):
        return rules_mod.RuleSet([
            rules_mod.parse_rule("||ads.example.net^"),
            rules_mod.parse_rule("||metrics.example.net^"),
            rules_mod.parse_rule("@@||cdn.example.net^"),
            rules_mod.parse_rule("/^acr[0-9]+\\.example$/"),
        ])

    def test_translates_block_rules(self):
        text, skipped = RouterDriver.build_include(self._rules())
        self.assertIn("address=/ads.example.net/0.0.0.0", text)
        self.assertIn("address=/metrics.example.net/0.0.0.0", text)

    def test_skips_allow_and_regex_rules(self):
        text, skipped = RouterDriver.build_include(self._rules())
        self.assertNotIn("cdn.example.net", text)
        self.assertEqual(skipped, 1)

    def test_empty_rule_set(self):
        text, skipped = RouterDriver.build_include(rules_mod.RuleSet())
        self.assertEqual(skipped, 0)
        self.assertIn("generated by dnsguard", text)


class DeployTests(unittest.TestCase):
    def setUp(self):
        self.folder = tempfile.TemporaryDirectory()
        self.addCleanup(self.folder.cleanup)
        self.runner = FakeRunner()
        self.driver = RouterDriver({
            "host": "192.0.2.1",
            "user": "root",
            "remote_dir": "/etc/dnsmasq.d",
            "remote_file": "toney.conf",
            "backup_dir": self.folder.name,
        }, runner=self.runner)

    def _rules(self):
        return rules_mod.RuleSet([rules_mod.parse_rule("||ads.example.net^")])

    def test_not_configured(self):
        driver = RouterDriver({}, runner=self.runner)
        with self.assertRaises(RouterError):
            driver.deploy(self._rules())

    def test_deploy_writes_the_file_and_restarts(self):
        result = self.driver.deploy(self._rules())
        self.assertTrue(result["deployed"])
        commands = [" ".join(call[0]) for call in self.runner.calls]
        self.assertTrue(any("cat > /etc/dnsmasq.d/toney.conf" in c for c in commands))
        self.assertTrue(any("dnsmasq restart" in c for c in commands))
        payload = self.runner.calls[2][1]
        self.assertIn(b"address=/ads.example.net/0.0.0.0", payload)

    def test_deploy_backs_up_the_previous_file(self):
        self.driver.deploy(self._rules())
        backups = [n for n in os.listdir(self.folder.name) if n.endswith(".conf")]
        self.assertEqual(len(backups), 1)

    def test_rollback_restores_the_backup(self):
        self.driver.deploy(self._rules())
        self.driver._rules = self._rules()
        result = self.driver.rollback()
        self.assertTrue(result["rolled_back"])
        self.assertFalse(result["removed"])

    def test_rollback_without_a_backup_removes_the_file(self):
        result = self.driver.rollback()
        self.assertTrue(result["removed"])
        commands = [" ".join(call[0]) for call in self.runner.calls]
        self.assertTrue(any("rm -f /etc/dnsmasq.d/toney.conf" in c for c in commands))

    def test_status_reports_a_missing_file(self):
        runner = FakeRunner({"cat": "__MISSING__\n"})
        driver = RouterDriver({"host": "192.0.2.1"}, runner=runner)
        status = driver.status(self._rules())
        self.assertTrue(status["configured"])
        self.assertFalse(status["installed"])

    def test_status_compares_the_installed_file(self):
        text, _ = RouterDriver.build_include(self._rules())
        runner = FakeRunner({"cat": text})
        driver = RouterDriver({"host": "192.0.2.1"}, runner=runner)
        status = driver.status(self._rules())
        self.assertTrue(status["installed"])
        self.assertTrue(status["matches"])

    def test_failures_become_router_errors(self):
        def failing(command, stdin=None, timeout=None):
            raise RouterError("host unreachable")
        driver = RouterDriver({"host": "192.0.2.1"}, runner=failing)
        with self.assertRaises(RouterError):
            driver.deploy(self._rules())


if __name__ == "__main__":
    unittest.main()
